using UnityEngine;

namespace ProtoSystem
{
    /// <summary>
    /// Помечает int-поле как ID события шины: инспектор рисует выпадающий список
    /// всех событий вместо голого числа.
    ///
    /// Список собирается рефлексией по ВСЕМ загруженным сборкам, поэтому в него
    /// попадают и события пакета (ProtoSystem.Evt, 10000+), и события проекта
    /// (например LastConvoy.Evt, 1000+) — пакету не нужно знать о проекте.
    ///
    /// Зачем не строка-имя: событие в шине — это int, и любой резолв по имени
    /// падал бы в рантайме. Число же ломается молча при перенумерации, поэтому
    /// drawer показывает рядом с числом человекочитаемый путь.
    /// </summary>
    public class EventIdAttribute : PropertyAttribute
    {
    }
}
